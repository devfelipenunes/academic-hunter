#!/usr/bin/env python3
"""Overlap analysis: compare DOIs between keyword, embedding, and hybrid modes.

Reads the ablation results CSV files and computes:
- Shared papers (found by ALL modes)
- Unique papers (found by only ONE mode)
- Pairwise overlap percentages

Usage:
    python papers/experiments/overlap_analysis.py
"""

import json
import sys
from pathlib import Path

SRC = Path(__file__).parent.parent.parent / "src"
sys.path.insert(0, str(SRC))

RESULTS_DIR = Path(__file__).parent / "results"
RESULTS_DIR.mkdir(exist_ok=True)


def load_dois_from_report(report_path: str) -> set:
    """Extract DOIs from a CSV dataset file generated by the pipeline."""
    # The report path points to RELATORIO_ELITE_*.md
    # The CSV is in the same run directory
    run_dir = Path(report_path).parent
    if not run_dir.exists():
        run_dir = Path("results") / report_path.split("RELATORIO_ELITE_")[-1].replace(".md", "")

    csv_files = list(Path("results").rglob(f"*{report_path.split('_')[-1].replace('.md', '')}*.csv"))

    dois = set()
    for csv_file in csv_files:
        if csv_file.exists():
            with open(csv_file) as f:
                header = f.readline().strip().split(",")
                doi_idx = header.index("DOI") if "DOI" in header else -1
                if doi_idx < 0:
                    continue
                for line in f:
                    parts = line.strip().split(",")
                    if len(parts) > doi_idx:
                        doi = parts[doi_idx].strip().strip('"')
                        if doi:
                            dois.add(doi)
    return dois


def main():
    # Load ablation results
    results_path = RESULTS_DIR / "ablation_results.json"
    if not results_path.exists():
        print("❌ Run ablation experiment first: python papers/experiments/run_ablation.py")
        return

    results = json.loads(results_path.read_text())

    if len(results) < 3:
        print("⚠️  Only %d modes available. Run all 3 modes for full overlap analysis." % len(results))

    # Collect DOIs per mode from their CSV datasets
    mode_dois = {}
    for r in results:
        mode = r["mode"]
        report = r.get("report", "")
        dois = set()

        # Try to find CSV in results directory
        timestamp = report.split("_")[-1].replace(".md", "") if report else ""
        csv_pattern = f"academic_dataset_{timestamp}.csv"
        csv_files = list(Path("results").rglob(csv_pattern))

        for csv_file in csv_files:
            if csv_file.exists():
                with open(csv_file) as f:
                    header = f.readline().strip().split(",")
                    doi_idx = header.index("DOI") if "DOI" in header else -1
                    if doi_idx < 0:
                        continue
                    for line in f:
                        parts = line.strip().split(",")
                        if len(parts) > doi_idx:
                            doi = parts[doi_idx].strip().strip('"')
                            if doi:
                                dois.add(doi)

        # Also try the run directories
        if not dois:
            run_dirs = sorted(Path("results").glob(f"run_*{timestamp}*"))
            for d in run_dirs:
                for csv_file in d.glob("*.csv"):
                    with open(csv_file) as f:
                        header = f.readline().strip().split(",")
                        doi_idx = header.index("DOI") if "DOI" in header else -1
                        if doi_idx < 0:
                            continue
                        for line in f:
                            parts = line.strip().split(",")
                            if len(parts) > doi_idx:
                                doi = parts[doi_idx].strip().strip('"')
                                if doi:
                                    dois.add(doi)

        mode_dois[mode] = dois
        print(f"  {mode}: {len(dois)} DOIs found" if dois else f"  {mode}: ⚠️ no DOIs found (check report path: {report})")

    if len(mode_dois) < 2:
        print("❌ Need at least 2 modes with DOIs for overlap analysis.")
        return

    # Compute overlaps
    mode_names = list(mode_dois.keys())

    print(f"\n{'='*60}")
    print(f"  OVERLAP ANALYSIS")
    print(f"{'='*60}\n")

    # All shared
    shared = set.intersection(*mode_dois.values()) if len(mode_dois) > 1 else set()
    all_papers = set.union(*mode_dois.values())

    print(f"  Total unique papers across all modes: {len(all_papers)}")
    print(f"  Shared by ALL modes: {len(shared)} ({len(shared)/len(all_papers)*100:.1f}%)" if all_papers else "")
    print()

    # Per-mode stats
    for mode in mode_names:
        others = set.union(*[v for k, v in mode_dois.items() if k != mode])
        unique = mode_dois[mode] - others
        shared_with_any = mode_dois[mode] & others
        print(f"  {mode}:")
        print(f"    Total: {len(mode_dois[mode])}")
        print(f"    Unique to this mode: {len(unique)} ({len(unique)/len(mode_dois[mode])*100:.1f}%)" if mode_dois[mode] else "")
        print(f"    Shared with at least one other: {len(shared_with_any)}")
        print()

    # Pairwise
    for i, m1 in enumerate(mode_names):
        for m2 in mode_names[i+1:]:
            overlap = mode_dois[m1] & mode_dois[m2]
            jaccard = len(overlap) / len(mode_dois[m1] | mode_dois[m2]) if (m1 in mode_dois and m2 in mode_dois) else 0
            print(f"  {m1} ∩ {m2}: {len(overlap)} shared (Jaccard: {jaccard:.3f})")

    # Save
    out = RESULTS_DIR / "overlap_analysis.json"
    out.write_text(json.dumps({
        "total_unique_papers": len(all_papers),
        "shared_by_all": len(shared),
        "modes": {m: {"total": len(d), "unique": len(d - set.union(*[v for k, v in mode_dois.items() if k != m]))} for m, d in mode_dois.items()},
        "pairwise": {f"{m1}_vs_{m2}": len(mode_dois[m1] & mode_dois[m2]) for i, m1 in enumerate(mode_names) for m2 in mode_names[i+1:]},
    }, indent=2))
    print(f"\n✅ Results saved to {out}")


if __name__ == "__main__":
    main()
